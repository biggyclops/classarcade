import test from'node:test';import assert from'node:assert/strict';import{DatabaseSync}from'node:sqlite';import{readFileSync}from'node:fs';import{adapter}from'./sqlite-adapter.mjs';import{api}from'./api.mjs';
test('invite-only teachers, class isolation, PIN saves, board moderation, cross-class approval',async()=>{
 const sqlite=new DatabaseSync(':memory:');sqlite.exec(readFileSync(new URL('./schema.sql',import.meta.url),'utf8'));const env={DB:adapter(sqlite),ADMIN_INVITE:'local-test-owner-invite',OWNER_EMAIL:'owner@example.test'};
 async function call(path,body,token,status=200){const r=await api(new Request('https://test.local/api/next-chapter'+path,{method:body===undefined?'GET':'POST',headers:{...(token?{Authorization:'Bearer '+token}:{}),'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)}),env),d=await r.json();assert.equal(r.status,status,JSON.stringify(d));return d;}
 await call('/teacher/register',{invite:'no',username:'bad',email:'bad@example.test',password:'long-enough-password'},null,403);
 const owner=await call('/teacher/register',{invite:env.ADMIN_INVITE,username:'owner',email:'owner@example.test',password:'long-enough-password'});
 const ca=await call('/classes',{name:'Class A'},owner.token);
 const inv=await call('/invites',{email:'other@example.test'},owner.token);
 const other=await call('/teacher/register',{invite:inv.invite,username:'other',email:'other@example.test',password:'long-enough-password'});
 await call('/teacher/register',{invite:inv.invite,username:'third',email:'other@example.test',password:'long-enough-password'},null,403);
 const cb=await call('/classes',{name:'Class B'},other.token);
 await call('/class/report?classId='+ca.id,undefined,other.token,404);
 const a=await call('/student/join',{code:ca.code,nickname:'alex',pin:'123456'}),b=await call('/student/join',{code:cb.code,nickname:'sam',pin:'456789'});
 await call('/game/start',{name:'Alex',scenario:'family',avatar:2},a.token);await call('/game/start',{name:'Sam',scenario:'family'},b.token);
 await call('/student/join',{code:ca.code,nickname:'alex',pin:'999999'},null,401);
 const resume=await call('/student/join',{code:ca.code,nickname:'alex',pin:'123456'});assert.equal((await call('/game',undefined,resume.token)).game.profile.name,'Alex');
 await call('/board',{body:'Looking for a reliable roommate',budget:1100,area:'Lowell',moveMonth:'2'},a.token);
 assert.equal((await call('/board',undefined,b.token)).posts.length,0);
 const report=await call('/class/report?classId='+ca.id,undefined,owner.token);
 await call('/board/moderate',{id:report.posts[0].id,approve:true},other.token,404);
 await call('/board/moderate',{id:report.posts[0].id,approve:true},owner.token);
 assert.equal((await call('/board',undefined,b.token)).posts.length,0);
 await call('/classes/connect',{classId:ca.id,code:cb.code},owner.token);
 const links=(await call('/class/report?classId='+cb.id,undefined,other.token)).links;
 await call('/classes/connect/respond',{id:links[0].id,accept:true},other.token);
 assert.equal((await call('/board',undefined,b.token)).posts.length,1);
 await call('/roommates/request',{friendCode:b.user.friendCode},a.token);
 const pair=(await call('/board',undefined,b.token)).pairs[0];assert.equal(pair.active,0);
 await call('/roommates/respond',{id:pair.id,accept:true},b.token);
 await call('/roommates/approve',{classId:ca.id,id:pair.id,approve:true},owner.token);
 assert.equal((await call('/board',undefined,a.token)).pairs[0].active,0);
 await call('/roommates/approve',{classId:cb.id,id:pair.id,approve:true},other.token);
 assert.equal((await call('/board',undefined,a.token)).pairs[0].active,1);
 assert.equal((await call('/board',undefined,a.token)).pairs[0].state,undefined);
 await call('/class/settings',{classId:ca.id,paused:true,autoCalculate:false},owner.token);
 await call('/game/action',{type:'goal',goal:5000},a.token,400);
 assert.equal((await call('/game',undefined,a.token)).settings.autoCalculate,false);
 await call('/listings/refresh',{classId:ca.id},owner.token,503);
 sqlite.close();
});
